// The exploding turbine behind the homepage: turbine.dc.html beside this file is the
// design's verbatim template, whose {{bindings}} become CSS variables and data hooks
// that staticfiles/js/turbine.js fills in as the page scrolls.
// Run: node build.mjs   writes staticfiles/image/turbine/turbine.svg
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const HERE = dirname(fileURLToPath(import.meta.url));
const OUT = join(HERE, "../../staticfiles/image/turbine");
const HEADER = "<!-- Generated by figures/turbine/build.mjs from turbine.dc.html. Edit the build, not this file. -->\n";

const REWRITES = [
  [/^<svg\b([^>]*?) style="[^"]*"/, '<svg xmlns="http://www.w3.org/2000/svg"$1'],
  [/transform="\{\{cam\}\}"/g, 'data-cam=""'],
  [/transform="\{\{t\.bladeR\}\}"/g, 'data-blade=""'],
  [/transform="\{\{L\.(\w+)\.t\}\}" opacity="\{\{L\.\1\.o\}\}"/g, 'data-callout="$1" opacity="0"'],
  [/transform="\{\{t\.(\w+)\}\}"/g, 'data-part="$1"'],
  [/opacity="\{\{bladeOp\}\}"/g, 'data-fade="blade"'],
  [/opacity="\{\{baseOp\}\}"/g, 'data-fade="base"'],
  [/\{\{beaconOp\}\}/g, "var(--tb-beacon-op)"],
  [/\{\{c\.(\w+)\}\}/g, "var(--tb-$1)"],
  [/&(?!(?:amp|lt|gt|quot|apos|#\d+|#x[\da-fA-F]+);)/g, "&amp;"],
];

const source = readFileSync(join(HERE, "turbine.dc.html"), "utf8");
const svg = source.match(/<svg\b[\s\S]*?<\/svg>/)?.[0];
if (!svg) throw new Error("turbine.dc.html has no <svg>");

const out = REWRITES.reduce((text, [pattern, replacement]) => text.replace(pattern, replacement), svg);

const survivor = out.match(/\{\{[^}]*\}\}|\{\{/);
if (survivor) throw new Error(`unhandled binding in turbine.dc.html: ${survivor[0]}`);

mkdirSync(OUT, { recursive: true });
writeFileSync(join(OUT, "turbine.svg"), HEADER + out + "\n");
